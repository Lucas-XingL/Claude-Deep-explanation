#!/usr/bin/env node
// Teach an anatomy-reveal project to build one film page per storyboard shot.
//
//   node setup_shots.mjs <anatomy-reveal project dir>
//
// Writes, next to the template's own files:
//   motion/timeline-core.mjs  the template's timeline engine without its espresso keys
//   motion/build-shot.mjs     build.mjs + --shot <file.mjs> --timeline <timeline.json> --id <Sxx> [--out …]
// A shot file exports make(shot) → { keys, labels } in seconds; shot is that entry of
// audio/timeline.json (duration, lines with times relative to the shot). The page runs for
// exactly shot.duration, so the template's retimer leaves the keys alone.
// It patches the template's text, so it stops with a clear error if the template changed.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = resolve(process.argv[2] ?? "");
const mf = (p) => join(dir, "motion", p);
if (!existsSync(mf("build.mjs")) || !existsSync(mf("timeline.mjs"))) {
  console.error(`not an anatomy-reveal project (no motion/build.mjs, motion/timeline.mjs): ${dir}`);
  process.exit(1);
}
const need = (text, anchor, what) => {
  if (!text.includes(anchor)) {
    console.error(`template changed: cannot find ${what}:\n  ${anchor.slice(0, 90)}`);
    process.exit(1);
  }
};

// 1. timeline-core.mjs: everything in timeline.mjs except BASE_DURATION / BASE_KEYS / BASE_LABELS.
const tl = readFileSync(mf("timeline.mjs"), "utf8");
need(tl, "export const BASE_DURATION", "BASE_DURATION in timeline.mjs");
need(tl, "const REQUESTED", "REQUESTED in timeline.mjs");
const core = tl.slice(0, tl.indexOf("export const BASE_DURATION")) + tl.slice(tl.indexOf("const REQUESTED"));
writeFileSync(mf("timeline-core.mjs"), "// timeline.mjs without its keys; build-shot.mjs prepends a shot's keys. Generated by setup_shots.mjs.\n" + core);

// 2. build-shot.mjs
let b = readFileSync(mf("build.mjs"), "utf8");
const A1 = 'const duration = flag("duration") ? Number(flag("duration")) : undefined;';
need(b, A1, "the duration flag");
b = b.replace(A1, A1.replace("const duration", "let duration"));
const A2 = 'const timeline = source(join(HERE, "timeline.mjs"));';
need(b, A2, "the timeline source line");
b = b.replace(A2, `// --shot <file.mjs> --timeline <audio/timeline.json> --id <Sxx>: one page per storyboard shot.
const shotFile = flag("shot");
let timeline;
let outName = "motion.html";
if (shotFile) {
  const { resolve: res } = await import("node:path");
  const { pathToFileURL } = await import("node:url");
  const tlj = JSON.parse(readFileSync(res(flag("timeline")), "utf8"));
  const shot = tlj.shots.find((s) => s.id === flag("id"));
  if (!shot) throw new Error(\`shot \${flag("id")} not in \${flag("timeline")}\`);
  const mod = await import(pathToFileURL(res(shotFile)).href);
  const { keys, labels } = mod.make(shot);
  if (!keys?.length || keys[0].t !== 0) throw new Error("make(shot).keys must start with a key at t = 0 that sets every channel");
  timeline = \`const BASE_DURATION = \${shot.duration};\\nconst BASE_KEYS = \${JSON.stringify(keys)};\\nconst BASE_LABELS = \${JSON.stringify(labels ?? [{ t: 0, hint: "", readout: "" }])};\\n\` + source(join(HERE, "timeline-core.mjs"));
  outName = flag("out") ?? \`shots/\${shot.id}.html\`;
  duration = shot.duration;
} else timeline = source(join(HERE, "timeline.mjs"));`);
const A3 = 'writeFileSync(join(HERE, "motion.html"), page);';
need(b, A3, "the page write");
b = b.replace(A3, 'const { mkdirSync: mk } = await import("node:fs");\nmk(dirname(join(HERE, outName)), { recursive: true });\nwriteFileSync(join(HERE, outName), page);');
const A4 = "console.log(`wrote motion.html";
need(b, A4, "the final log line");
b = b.replace(A4, "console.log(`wrote ${outName}");
writeFileSync(mf("build-shot.mjs"), "// Generated by explainer-video/scripts/anatomy/setup_shots.mjs from build.mjs.\n" + b);
console.log(`wrote ${mf("timeline-core.mjs")}\nwrote ${mf("build-shot.mjs")}`);
