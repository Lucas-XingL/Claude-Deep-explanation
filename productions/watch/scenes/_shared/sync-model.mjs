// Copies the movement model (WATCH + movement()) from the anatomy object's film.mjs into model.js,
// so the 2D scenes and the anatomy shots run on exactly the same numbers.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const HERE = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(HERE, "movement/object/film.mjs"), "utf8");
const body = src.slice(0, src.indexOf("export const FILM")).replace(/^export /gm, "");
writeFileSync(join(HERE, "model.js"), `// Generated by sync-model.mjs from movement/object/film.mjs. Do not edit.\n${body}\nwindow.WATCH = WATCH;\nwindow.movement = movement;\n`);
console.log("wrote model.js");
